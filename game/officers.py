def _gender(text: str, female: bool) -> str:
    import re
    return re.sub(r"\{([^|{}]*)\|([^|{}]*)\}", lambda m: m.group(2 if female else 1), text)


def bio(o: Officer) -> str:
    """Short story of the officer (2-4 sentences), true to his stats."""
    if o.rank == 0:
        return _LEADER_BIO[o.faction]
    r = random.Random(f"bio:{o.key}:{o.name}")
    order = sorted(range(len(STATS)), key=lambda i: o.stats[i])
    best, worst = STATS[order[-1]], STATS[order[0]]
    origins = list(_ORIGIN[o.faction])
    random.Random(f"bio:{o.faction}").shuffle(origins)       # neighbours in the list get different pasts
    i = int(o.key.split(":")[1])
    parts = [origins[i % len(origins)], r.choice(_STRONG[best])]
    if o.stats[order[0]] <= 8:
        parts.append(r.choice(_WEAK[worst]))
    quirks = _GOBLIN_QUIRK + _QUIRK[:4] if o.faction == "goblin" else _QUIRK
    if len(parts) < 3 or r.random() < 0.35:
        parts.append(r.choice(quirks))
    from .cards import VICE_OF, VICE_TRAIT
    for v in VICE_OF.get(o.key, ()):
        parts.append(VICE_TRAIT[v])
    return _gender(" ".join(parts), o.female)
