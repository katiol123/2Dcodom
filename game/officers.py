# leadership ranges by rank
_LEADERSHIP = {0: (760, 800), 1: (480, 620), 2: (330, 470), 3: (200, 340)}


def _rank(i: int) -> int:
    return 0 if i == 0 else 1 if i <= 4 else 2 if i <= 10 else 3


def _build() -> Dict[str, List[Officer]]:
    out: Dict[str, List[Officer]] = {}
    for f in ALL_FACTIONS:
        good, bad = _BENT[f.key]
        lst = []
        for i, raw in enumerate(_NAMES[f.key]):
            female = raw.startswith("*")
            name = raw.lstrip("*")
            r = random.Random(f"officer:{f.key}:{name}")
            rank = _rank(i)
            lo, hi = _LEADERSHIP[rank]
            leadership = int(round(r.uniform(lo, hi) / 10) * 10)
            stats = []
            for st in STATS:
                v = r.gauss(9, 2.8) + (4 if st in good else 0) - (4 if st in bad else 0) + (3 - rank) * 1.4
                stats.append(max(1, min(20, int(round(v)))))
            if rank == 0:
                title = f.leader_title
                look = _LEADER_LOOK[f.key]
            else:
                title = _TITLES[f.key][rank - 1][1 if female else 0]
                look = r.choice(_LOOKS[f.key])
            lst.append(Officer(f"{f.key}:{i}", name, title, f.key, rank, leadership, tuple(stats), look, female))
        out[f.key] = lst
    return out


OFFICERS: Dict[str, List[Officer]] = _build()
OFFICER: Dict[str, Officer] = {o.key: o for lst in OFFICERS.values() for o in lst}

