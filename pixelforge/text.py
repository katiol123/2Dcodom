# Cyrillic letters identical to Latin glyphs
for cyr, lat in zip("АВЕЁЗКМНОРСТХ", "ABEE3KMHOPCTX"):
    _RAW[cyr] = _RAW[lat]

FONT: Dict[str, List[str]] = {k: v.split("|") for k, v in _RAW.items()}
HEIGHT = 5


def glyph(ch: str) -> List[str]:
    return FONT.get(ch.upper(), FONT["?"])


def text_width(s: str, spacing: int = 1) -> int:
    if not s:
        return 0
    return sum(len(glyph(c)[0]) + spacing for c in s) - spacing


def draw_text(grid: Grid, s: str, x: int, y: int, color: ColorLike,
              shadow: Optional[ColorLike] = None, spacing: int = 1) -> int:
    """Draw ``s`` with its top-left at (x, y); returns the end x."""
    col = rgba(color) if hasattr(grid, "to_image") else color
    sh = None if shadow is None else (rgba(shadow) if hasattr(grid, "to_image") else shadow)
    cx = x
    for ch in s:
        g = glyph(ch)
        if sh is not None:
            grid.stamp(g, cx + 1, y + 1, {"#": sh})
        grid.stamp(g, cx, y, {"#": col})
        cx += len(g[0]) + spacing
    return cx - spacing
